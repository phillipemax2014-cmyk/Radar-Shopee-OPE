export function buildMockProducts(): ShopeeProduct[] {
  const now = new Date();
  const formattedDate = `Atualizado em ${now.toLocaleDateString('pt-BR')} às ${now.toLocaleTimeString('pt-BR', { hour: '2-digit', minute: '2-digit' })}`;

  return RAW_MOCK_PRODUCTS.map((raw, index) => {
    const { score, isGoldMine, badgeLabel, reasons } = calculateOpportunityScore(raw);
    const commissionVal = raw.commissionRate ? Number(((raw.price * raw.commissionRate) / 100).toFixed(2)) : null;

    // Simulate realistic recent 7-day sales trend proportional to monthlySales
    const avgDaily = Math.max(2, Math.round(raw.monthlySales / 30));
    const days = ['6d atrás', '5d atrás', '4d atrás', '3d atrás', '2d atrás', 'Ontem', 'Hoje'];
    const salesHistory = days.map((day, dIdx) => {
      const factor = 0.85 + (dIdx * 0.05) + (Math.sin(dIdx + index) * 0.12);
      return {
        label: day,
        sales: Math.max(1, Math.round(avgDaily * factor)),
      };
    });

    return {
      id: raw.id,
      itemId: raw.itemId,
      item_id: raw.itemId,
      shopId: raw.shopId,
      shop_id: raw.shopId,
      title: raw.title,
      category: raw.category,
      price: raw.price,
      originalPrice: raw.originalPrice,
      salesCount: raw.salesCount,
      vendasTotais: raw.salesCount,
      salesDisplay: formatNumberBR(raw.salesCount),
      monthlySales: raw.monthlySales,
      salesHistory,
      videoCount: raw.videoCount,
      videoSource: raw.videoSource,
      videoNotes: raw.videoNotes,
      stock: raw.stock,
      stockStatus: raw.stockStatus,
      stockTurnoverDays: raw.stockTurnoverDays,
      commissionRate: raw.commissionRate,
      commissionValue: commissionVal,
      rating: raw.rating,
      ratingCount: raw.ratingCount,
      affiliateCount: raw.affiliateCount,
      productUrl: raw.productUrl,
      product_url: raw.productUrl,
      affiliateUrl: raw.affiliateUrl,
      affiliate_link: raw.affiliateUrl,
      imageUrl: raw.imageUrl,
      opportunityScore: score,
      isGoldMine,
      badgeLabel,
      reasons,
      isMock: true,
      lastUpdated: formattedDate,
      availableFields: {
        sales: true,
        salesHistory: true,
        videos: true,
        stock: true,
        commission: true,
        affiliates: true,
        rating: true,
      },
    };
  });
}
